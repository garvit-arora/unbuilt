  "inline-flex h-5 shrink-0 items-center gap-1 rounded-full border px-2 text-[11px] font-medium leading-none whitespace-nowrap [&>svg]:size-3";

type ChipProps = { className?: string };

export function DemoChip({ className }: ChipProps) {
  return (
    <span
      className={cn(chip, "border-warning/40 bg-warning/10 text-warning", className)}
      title="Synthetic demo record created by the seed script. Not a real person or real activity."
    >
      <FlaskConical aria-hidden />
      Demo data
    </span>
  );
}

