/**
 * Cluster blueprints (design 7.4 Agent 4, 11 Blueprint tab, 12 blueprint routes). Every generation is a new
 * `cluster_blueprints` version; older versions stay readable. Markdown is rendered once at write time by the pure
 * `toMarkdown`, with a provenance label (Fallback AI / AI-generated / Demo blueprint).
 */

/** Pure Markdown export of a blueprint. */
export function toMarkdown(title: string, blueprint: Blueprint, label?: string): string {
  return blueprintToMarkdown(title, blueprint, label);
}

export function provenanceLabel(provider: "llm" | "fallback", model: string): string {
  return provider === "llm"
    ? `AI-generated by ${model}. Review before relying on it.`
    : `Fallback AI: assembled by UNBUILT's deterministic template (${model}) from the cluster's stored data; no language model was used.`;
}

/** Most common suggested product type among the linked wishes (ties: alphabetical). */
export function dominantProductType(types: readonly ProductType[]): ProductType | null {
  const counts = new Map<ProductType, number>();
  for (const t of types) counts.set(t, (counts.get(t) ?? 0) + 1);
  const ranked = [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  return ranked[0]?.[0] ?? null;
}

async function architectInput(cluster: ClusterRecord): Promise<ArchitectInput> {
  const cached = await getServiceClient().from("demand_clusters").select("metrics_cache, metrics_refreshed_at").eq("id", cluster.id).single();
  if (cached.error) dbFail("blueprint metrics lookup failed", cached.error);
  const [metrics, features, wishes] = await Promise.all([
    getClusterMetrics({ id: cluster.id, metricsCache: cached.data.metrics_cache, metricsRefreshedAt: cached.data.metrics_refreshed_at }, { checkEvents: true }),
    supabaseFeaturesRepo.listByCluster(cluster.id),
    loadLinkedWishes(cluster.id),
  ]);
  const consensus = new Map((metrics?.featureConsensus ?? []).map((f) => [f.featureId, f]));
  return {
    cluster: {
      id: cluster.id,
      title: cluster.title,
      description: cluster.description,
      problemStatement: cluster.problemStatement,
      targetAudience: cluster.targetAudience,
      category: cluster.category,
      difficulty: cluster.difficulty,
    },
    features: features
      .filter((f) => f.status === "active" || f.status === "emerging")
      .map((f) => ({ title: f.title, kind: f.kind, status: f.status, mentionPct: consensus.get(f.id)?.mentionPct ?? 0, explicitPct: consensus.get(f.id)?.explicitPct ?? 0 })),
    constraintTags: cluster.constraints.tags as ConstraintTag[],
    constraintNotes: cluster.constraints.notes,
    uniqueInterested: metrics?.uniqueInterested ?? 0,
    wtp: { n: metrics?.wtp.n ?? 0, medianCents: metrics?.wtp.sufficient ? metrics.wtp.medianCents : null },
    productType: dominantProductType(wishes.map((w) => w.intent.suggestedProductType)),
  };
}

type BlueprintRow = {
  id: string;
  cluster_id: string;
  version: number;
  provider: "llm" | "fallback";
  is_demo: boolean;
  markdown: string;
  created_at: string;
  ai_analysis_runs: { model_name: string } | null;
};

const COLUMNS = "id, cluster_id, version, provider, is_demo, markdown, created_at, ai_analysis_runs(model_name)";

function toView(row: BlueprintRow): BlueprintView {
  return {
    id: row.id,
    clusterId: row.cluster_id,
    version: row.version,
    provider: row.provider,
    modelName: row.ai_analysis_runs?.model_name ?? (row.is_demo ? "seed-curated-v1" : null),
    isDemo: row.is_demo,
    markdown: row.markdown,
    createdAt: row.created_at,
  };
}

/** All versions of a cluster's blueprint, newest first. */
export async function listBlueprints(clusterId: string): Promise<BlueprintView[]> {
  const { data, error } = await getServiceClient().from("cluster_blueprints").select(COLUMNS).eq("cluster_id", clusterId).order("version", { ascending: false });
  if (error) dbFail("cluster_blueprints list failed", error);
  return (data as unknown as BlueprintRow[]).map(toView);
}

export async function getBlueprint(clusterId: string, version?: number): Promise<BlueprintView | null> {
  let query = getServiceClient().from("cluster_blueprints").select(COLUMNS).eq("cluster_id", clusterId);
  query = version ? query.eq("version", version) : query.order("version", { ascending: false }).limit(1);
  const { data, error } = await query.maybeSingle();
  if (error) dbFail("cluster_blueprints lookup failed", error);
  return data ? toView(data as unknown as BlueprintRow) : null;
}

const MAX_VERSION_ATTEMPTS = 3;

async function insertNextVersion(row: { clusterId: string; content: Blueprint; markdown: string; provider: "llm" | "fallback"; aiRunId: string; createdBy: string }) {
  const db = getServiceClient();
  for (let attempt = 1; attempt <= MAX_VERSION_ATTEMPTS; attempt += 1) {
    const latest = await db.from("cluster_blueprints").select("version").eq("cluster_id", row.clusterId).order("version", { ascending: false }).limit(1).maybeSingle();
    if (latest.error) dbFail("cluster_blueprints version lookup failed", latest.error);
    const version = (latest.data?.version ?? 0) + 1;
    const { data, error } = await db
      .from("cluster_blueprints")
      .insert({
        cluster_id: row.clusterId,
        version,
        content: row.content as unknown as NonNullable<Json>,
        markdown: row.markdown,
        provider: row.provider,
        ai_run_id: row.aiRunId,
        created_by: row.createdBy,
        is_demo: false,
      })
      .select(COLUMNS)
      .single();
    // 23505 = another generation took this version number concurrently; read the max again.
    if (error?.code === "23505" && attempt < MAX_VERSION_ATTEMPTS) continue;
    if (error) dbFail("cluster_blueprints insert failed", error);
    return toView(data as unknown as BlueprintRow);
  }
  throw new AppError("CONFLICT", 409, "Could not allocate a blueprint version. Try again.");
}

export type BlueprintDeps = { architect: ProductArchitect };

/** `POST /api/ai/blueprint` (builder|admin): runs Agent 4 and stores the result as the next version. */
export async function generateBlueprint(actor: Pick<SessionUser, "id" | "role">, clusterRef: string, deps: BlueprintDeps = { architect: productArchitect }) {
  const cluster = await findVisibleCluster(clusterRef, actor);
  if (!cluster) throw new AppError("NOT_FOUND", 404, "Demand cluster not found.");
  const input = await architectInput(cluster);
  const result = await deps.architect.run(input, { actorId: actor.id });
  const markdown = toMarkdown(cluster.title, result.data, provenanceLabel(result.provider, result.model));
  const blueprint = await insertNextVersion({
    clusterId: cluster.id,
    content: result.data,
    markdown,
    provider: result.provider,
    aiRunId: result.runId,
    createdBy: actor.id,
  });
  logger.info("blueprint.generated", { clusterId: cluster.id, version: blueprint.version, provider: result.provider });
  await recordAudit({ actorId: actor.id, action: "blueprint.generate", entityType: "cluster", entityId: cluster.id, metadata: { version: blueprint.version, provider: result.provider } });
  return { blueprint, provider: result.provider, fallbackReason: result.fallbackReason };
}

/** File name of a Markdown export: `<slug>-blueprint-v<version>.md`. */
export function exportFileName(slug: string, version: number): string {
  return `${slug}-blueprint-v${version}.md`;
}

